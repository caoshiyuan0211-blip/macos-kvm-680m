#!/usr/bin/env python3
"""Generate src/RembrandtGfx/dcnremap.hpp: absolute register address pairs (DCN 3.0.2 -> DCN 3.1.2)
for every display register whose offset moved, so DAL's DCN 3.0.2 code reaches Rembrandt's DCN 3.1.2.

  dcn-remap.py   (reads src/linux-amd/asic_reg/dcn_3_0_2_offset.h, dcn_3_1_2_offset.h)
Both ASICs use DCN_BASE segments 0x12, 0xC0, 0x34C0, 0x9000, 0x02403C00.
"""
import re, os
SEG = [0x12, 0xC0, 0x34C0, 0x9000, 0x02403C00]
root = os.path.join(os.path.dirname(__file__), '..')
def load(f):
    d, base = {}, {}
    for l in open(os.path.join(root, 'src/linux-amd/asic_reg', f)):
        m = re.match(r'#define (?:reg|mm)(\w+?)(_BASE_IDX)?\s+(0x[0-9a-fA-F]+|\d+)\s*$', l)
        if not m: continue
        (base if m.group(2) else d)[m.group(1)] = int(m.group(3), 0)
    return {n: SEG[base[n]] + o for n, o in d.items() if n in base}
a, b = load('dcn_3_0_2_offset.h'), load('dcn_3_1_2_offset.h')
pairs = sorted((a[n], b[n], n) for n in set(a) & set(b) if a[n] != b[n])
# A 3.0.2 address must map to one target.
seen = {}
for s, t, n in pairs: seen.setdefault(s, set()).add(t)
pairs = [p for p in pairs if len(seen[p[0]]) == 1]
with open(os.path.join(root, 'src/RembrandtGfx/dcnremap.hpp'), 'w') as o:
    o.write('#pragma once\n// Generated by scripts/dcn-remap.py: DCN 3.0.2 -> 3.1.2 absolute register addresses.\n')
    o.write('struct DcnRemap { uint32_t from, to; const char *name; };\n')
    o.write('static const DcnRemap kDcnRemap[] {\n')
    for s, t, n in pairs: o.write(f'\t{{{s:#x}, {t:#x}, "{n}"}},\n')
    o.write('};\n')
print(len(pairs), 'remapped registers')
