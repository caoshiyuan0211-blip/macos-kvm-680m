#!/usr/bin/env python3
"""Generate a Navi 23 -> Rembrandt register address map from Linux amdgpu headers (MIT).

  regmap-gen.py LINUX-AMD-DIR OUT.hpp

Apple's framebuffer/accelerator hardcode Navi 23 (dimgrey cavefish) dword register addresses
(IP base[segment] + offset). For each register name present in both chips' headers, compute
both absolute addresses and emit the pairs that differ, sorted for binary search.
"""
import os, re, sys
from collections import defaultdict

# (Navi 23 header, Rembrandt header, IP base name in Navi 23 table, in Rembrandt table)
PAIRS = [
    ('gc_10_3_0', 'gc_10_3_0', 'GC_BASE', 'GC_BASE'),
    ('mmhub_2_0_0', 'mmhub_2_3_0', 'MMHUB_BASE', 'MMHUB_BASE'),
    ('athub_2_1_0', 'athub_2_1_0', 'ATHUB_BASE', 'ATHUB_BASE'),
    ('osssys_5_0_0', 'osssys_5_0_0', 'OSSSYS_BASE', 'OSSSYS_BASE'),
    ('hdp_5_0_0', 'hdp_5_2_1', 'HDP_BASE', 'HDP_BASE'),
    ('nbio_2_3', 'nbio_7_2_0', 'NBIO_BASE', 'NBIO_BASE'),
    ('dcn_3_0_2', 'dcn_3_1_2', 'DCN_BASE', 'DCN_BASE'),
    ('smuio_11_0_6', 'smuio_13_0_3', 'SMUIO_BASE', 'SMUIO_BASE'),
    ('vcn_3_0_0', 'vcn_3_0_0', 'VCN0_BASE', 'VCN_BASE'),
]

def ip_bases(path):
    text = open(path).read()
    bases = {}
    for m in re.finditer(r'struct IP_BASE (\w+) = \{ \{ \{ \{ ([^}]*)\}', text):
        bases[m.group(1)] = [int(x, 16) for x in m.group(2).split(',') if x.strip()]
    return bases

def regs(path):
    off, idx = {}, {}
    for m in re.finditer(r'#define\s+(?:mm|reg)(\w+?)(_BASE_IDX)?\s+(0x[0-9a-fA-F]+|\d+)', open(path).read()):
        (idx if m.group(2) else off)[m.group(1)] = int(m.group(3), 0)
    return {n: (o, idx[n]) for n, o in off.items() if n in idx}

def main():
    root, out = sys.argv[1], sys.argv[2]
    nb, yb = ip_bases(os.path.join(root, 'dcf_ip_offset.h')), ip_bases(os.path.join(root, 'yellow_carp_offset.h'))
    mapping, conflicts, stats = defaultdict(set), 0, []
    for nh, yh, nbase, ybase in PAIRS:
        nr = regs(os.path.join(root, 'asic_reg', nh + '_offset.h'))
        yr = regs(os.path.join(root, 'asic_reg', yh + '_offset.h'))
        common = set(nr) & set(yr)
        moved = 0
        for name in common:
            (no, ni), (yo, yi) = nr[name], yr[name]
            na, ya = nb[nbase][ni] + no, yb[ybase][yi] + yo
            if na != ya:
                mapping[na].add(ya)
                moved += 1
        stats.append(f'{nh}->{yh}: {len(nr)} / {len(yr)} regs, {len(common)} common, {moved} moved, {len(set(nr) - set(yr))} Navi-only')
    pairs = []
    for na, ys in sorted(mapping.items()):
        if len(ys) != 1:
            conflicts += 1
            continue
        pairs.append((na, ys.pop()))
    with open(out, 'w') as f:
        f.write('// Generated by scripts/regmap-gen.py from Linux amdgpu register headers (MIT).\n')
        f.write('// Navi 23 dword register address -> Rembrandt dword register address, sorted.\n#pragma once\n')
        f.write(f'static const uint32_t kRegMap[][2] = {{\n')
        for na, ya in pairs:
            f.write(f'\t{{{na:#x}, {ya:#x}}},\n')
        f.write('};\n')
    print('\n'.join(stats))
    print(f'{len(pairs)} mapped addresses, {conflicts} ambiguous skipped')

if __name__ == '__main__':
    main()
