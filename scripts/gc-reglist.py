#!/usr/bin/env python3
"""Build the GC config-register list for Linux-vs-macOS state comparison (gc_10_3_0 names, Rembrandt bases).

  gc-reglist.py LINUX-AMD-DIR OUT.txt OUT.hpp

Takes non-context, non-FIFO GC registers of segments 0/1 from config-type blocks and skips names
whose reads have side effects (DATA/FIFO/INDEX ports, perf counters, ucode ports).
"""
import re, sys
PREFIXES = ('SPI_', 'SQ_', 'TA_', 'TD_', 'TCP_', 'TCC_', 'TCI_', 'GCR_', 'GL1', 'GL2', 'GB_', 'GCVM_', 'GCMC_', 'GCUTCL2',
            'GRBM_', 'SH_MEM', 'CP_DEBUG', 'CP_CPC_', 'CP_MEC_', 'CP_ME_', 'CP_PFP_', 'CP_GFX_', 'CP_RB_', 'CP_INT', 'CP_PQ',
            'RLC_CGCG', 'RLC_CGTT', 'RLC_PG', 'RLC_CNTL', 'RLC_STAT', 'RLC_CP', 'RLC_SPM_', 'RLC_GPM_GENERAL', 'RLC_SAFE',
            'RLC_LB_', 'RLC_CSIB', 'RLC_GFX_INDEX', 'CB_HW', 'DB_DEBUG', 'DB_HW', 'PA_SC_ENHANCE', 'PA_SC_TILE', 'PA_SC_LINE_STIPPLE_STATE',
            'PA_CL_ENHANCE', 'PA_SU_', 'VGT_', 'GE_', 'CC_', 'GC_USER', 'UTCL1_', 'CHA_', 'CHC_', 'CHCG_', 'GUS_', 'GDS_CNTL',
            'COMPUTE_STATIC', 'COMPUTE_DISPATCH_TUNNEL', 'SX_DEBUG', 'CGTS_', 'CGTT_')
SKIP = re.compile(r'DATA|FIFO|INDEX|PERFCOUNTER|PERF_|UCODE|_ADDR_LO$|SCRATCH|_RD_|WPTR|RPTR|DOORBELL|TIMESTAMP|ECC|EDC|DSM')
def main():
    root, txt, hpp = sys.argv[1:4]
    bases = [0x1260, 0xA000]
    src = open(f'{root}/asic_reg/gc_10_3_0_offset.h').read()
    off = {m.group(1): int(m.group(2), 16) for m in re.finditer(r'#define mm(\w+)\s+(0x[0-9a-fA-F]+)\n', src)}
    idx = {m.group(1): int(m.group(2)) for m in re.finditer(r'#define mm(\w+)_BASE_IDX\s+(\d+)', src)}
    regs = []
    for n, o in off.items():
        if n.endswith('_BASE_IDX') or n not in idx or idx[n] > 1 or not n.startswith(PREFIXES) or SKIP.search(n):
            continue
        a = bases[idx[n]] + o
        if a < 0x20000:
            regs.append((a, n))
    regs = sorted(set(regs))
    open(txt, 'w').write(''.join(f'{a:#x} {n}\n' for a, n in regs))
    with open(hpp, 'w') as f:
        f.write('// Generated by scripts/gc-reglist.py. Dword register addresses for the GC state snapshot.\n#pragma once\n')
        f.write('static const uint32_t kGcSnapRegs[] = {\n' + ''.join(f'\t{a:#x},\n' for a, _ in regs) + '};\n')
    print(len(regs), 'registers')
main()
